"""T-012: one requirement ID per bullet of the master prompt, generated (never hand-edited) from the verbatim text.

Writes docs/REQUIREMENTS_DETAILED.md: every '- ' bullet and every numbered item of docs/MASTER_PROMPT.md gets an ID
REQ-<section>-<nn> (source order), with its lead-in sentence (the nearest preceding paragraph line, e.g.
"Support:") and the section-level group row of REQUIREMENTS_REGISTER.md that binds it. Statuses are NOT copied:
the group rows carry status and evidence; a bullet inherits them until it gets its own row there.
Run: .venv/Scripts/python.exe tools/docs/split_requirements.py   (deterministic: same input -> same IDs)
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "docs", "MASTER_PROMPT.md")
REG = os.path.join(ROOT, "REQUIREMENTS_REGISTER.md")
OUT = os.path.join(ROOT, "docs", "REQUIREMENTS_DETAILED.md")


def group_rows():
    """section -> [group IDs] from the register's '§' column ('7, 15' binds both)."""
    out = {}
    for line in open(REG, encoding="utf-8"):
        m = re.match(r"^\| (REQ-\d+) \| ([^|]+) \|", line)
        if not m:
            continue
        for sec in re.split(r"[,;]\s*", m.group(2).strip()):
            out.setdefault(sec.strip(), []).append(m.group(1))
    return out


def parent_for(section, groups):
    s = section
    while s:
        if s in groups:
            return ", ".join(groups[s])
        s = s.rsplit(".", 1)[0] if "." in s else ""
    return "-"


def main():
    groups = group_rows()
    section, title, lead = "0", "", ""
    counters, rows = {}, []
    in_code = False
    for raw in open(SRC, encoding="utf-8"):
        line = raw.rstrip("\n")
        if line.strip().startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        h = re.match(r"^(#{1,3})\s+(\d+(?:\.\d+)?)\.?\s+(.*)$", line)
        if h:
            section, title, lead = h.group(2), h.group(3).strip(), ""
            continue
        if re.match(r"^#{1,3}\s", line):                     # unnumbered sub-heading: keep section, new lead
            lead = line.lstrip("#").strip()
            continue
        b = re.match(r"^\s*(?:[-*]|\d+\.)\s+(.*)$", line)
        if b and section != "0":
            counters[section] = counters.get(section, 0) + 1
            rows.append(("REQ-%s-%02d" % (section, counters[section]), section, title, lead, b.group(1).strip(),
                         parent_for(section, groups)))
        elif line.strip():
            lead = line.strip()
    esc = lambda t: t.replace("|", "\\|")                     # noqa: E731
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# Requirements, one ID per bullet (generated)\n\n")
        fh.write("Generated by `tools/docs/split_requirements.py` from `docs/MASTER_PROMPT.md` (verbatim; T-012). "
                 "Do not edit by hand: re-run the tool. Each item is bound by the section-level group row in "
                 "`REQUIREMENTS_REGISTER.md` named in 'Group', which carries status and evidence until the item gets "
                 "its own row there. %d items.\n\n" % len(rows))
        fh.write("| ID | § | Section | Lead-in (verbatim) | Item (verbatim) | Group |\n|---|---|---|---|---|---|\n")
        for r in rows:
            fh.write("| %s | %s | %s | %s | %s | %s |\n" % tuple(esc(x) for x in r))
    print("%d items, %d sections, %d without a group row" % (len(rows), len(counters),
                                                              sum(1 for r in rows if r[5] == "-")))


if __name__ == "__main__":
    main()
